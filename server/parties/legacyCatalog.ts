export function legacyOptionsFor(
  game: PartyGameId,
  name: string
): PartyRecommendation[] | undefined {
  const records = projectTeams(teams.filter(
    team => team.game === game && team.origin === name
  ));
  if (!records.length) return undefined;
  return records.map(team => ({
    id: team.id,
    rank: team.originOrder as 1 | 2 | 3,
    title: team.title,
    members: team.members.map(({ targetChanges, ...member }) => member),
    synergy: team.synergy,
    targetChanges:
      team.members.find(member => member.name.ja === name)?.targetChanges ?? [],
    targetSummary: team.targetSummary,
    gameVersion: team.gameVersion,
    dataAsOf: team.dataAsOf,
    updatedAt: team.updatedAt,
    sourceLabel: team.sourceLabel,
    sourceUrl: team.sourceUrl,
    communitySources: team.communitySources,
  }));
}
