/** キャラクターが属する精査済みバッチ番号。未精査なら null。 */
export function batchIdFor(game: CatalogGameId, name: string): number | null {
  return batchIndex.get(game + ":" + name) ?? null;
}

/** 指定バッチの名前リスト（未定義バッチは空）。 */
export function batchNames(id: number): BatchNames {
  return REVIEWED_BATCHES[id] ?? EMPTY;
}
