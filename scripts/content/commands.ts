import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { contentManifest, contentRepository } from "../../server/content/repository";
import { exportCandidates, readiness, reportCoverage } from "../../server/content/coverage";
import {unresolvedTeamMembers} from "../../content/teams";
import { expectedCatalogIndex } from "./catalogIndex";
import { checkUiGate } from "./uiGate";

export function generatedManifestText() {
  // Public identity only; no original corpus, contexts or translation reviews in Pages.
  const manifest = contentManifest();
  return `// Generated by content:generate.\nexport const CONTENT_MANIFEST = ${JSON.stringify({ schemaVersion: manifest.schemaVersion,
    contentRevision: manifest.contentRevision, translationMode: manifest.translationMode, readyLanguages: manifest.readyLanguages }, null, 2)} as const;\n`;
}
export function generatedUiText(audience: "public" | "admin" = "public") {
  const index = contentRepository();
  const sources = [...index.sources.values()].filter(source => source.id.startsWith("ui.") && source.audience === audience).sort((a, b) => a.id.localeCompare(b.id));
  const entries = Object.fromEntries(sources.map(source => [source.id, {
    ja: source.ja, en: index.catalog.translations.en[source.id]?.text ?? source.ja,
    "zh-CN": index.catalog.translations["zh-CN"][source.id]?.text ?? source.ja,
  }]));
  const variables = Object.fromEntries(sources.filter(source => Object.keys(source.placeholders).length).map(source => [source.id, source.placeholders]));
  return `// Generated by content:generate. UI strings and variable types only; no review/context metadata.\nexport const UI_TEXT: Record<string, {ja: string; en: string; "zh-CN": string}> = ${JSON.stringify(entries, null, 2)};\nexport const UI_VARIABLES: Record<string, Record<string, "string" | "number">> = ${JSON.stringify(variables, null, 2)};\n`;
}
export function contentCommand(args: string[]): number {
  const [command, ...raw] = args;
  const options = raw[0] === "--" ? raw.slice(1) : raw;
  const index = contentRepository();
  const ui = command === "generate" ? undefined : checkUiGate(new Set(index.sources.keys()));
  const language = options[options.indexOf("--language") + 1];
  const validLanguage = language === "en" || language === "zh-CN";
  const output = (value: unknown) => console.log(JSON.stringify(value, null, 2));
  if (command === "report" && (options.length === 0 || options.join(" ") === "--format json")) {
    output({ manifest: contentManifest(), ui, unresolvedTeamMembers:unresolvedTeamMembers(), ...reportCoverage(index) }); return 0;
  }
  if (command === "export" && options.length === 2 && options[0] === "--language" && validLanguage) {
    output(exportCandidates(index, language)); return 0;
  }
  if (command === "ready" && options.length === 4 && options[0] === "--language" && validLanguage && options[2] === "--scope" && ["public", "admin"].includes(options[3]!)) {
    const result = readiness(index, language, options[3] as "public" | "admin");
    const legacyDisplay = options[3] === "public" ? ui!.legacyCompatibility : [];
    const unresolvedMembers=options[3]==="public"?unresolvedTeamMembers():[];
    if (legacyDisplay.length || unresolvedMembers.length) result.ready = false;
    output({ ...result, legacyDisplay, unresolvedMembers }); return result.structureIssues.length ? 1 : result.ready ? 0 : 2;
  }
  const target = resolve("client/src/content/manifest.ts");
  if (command === "generate" && !options.length) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, generatedManifestText());
    writeFileSync(resolve("client/src/content/ui.generated.ts"), generatedUiText());
    writeFileSync(resolve("client/src/content/ui.admin.generated.ts"), generatedUiText("admin"));
    console.log("content manifest generated"); return 0;
  }
  if (command === "check" && !options.length) {
    if (readFileSync(resolve("content/catalog.ts"), "utf8").replace(/\r\n/g, "\n") !== expectedCatalogIndex()) throw new Error("Catalog index differs");
    if (!existsSync(target) || readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== generatedManifestText()) throw new Error("Content manifest differs");
    if (readFileSync(resolve("client/src/content/ui.generated.ts"), "utf8").replace(/\r\n/g, "\n") !== generatedUiText()) throw new Error("UI strings differ");
    if (readFileSync(resolve("client/src/content/ui.admin.generated.ts"), "utf8").replace(/\r\n/g, "\n") !== generatedUiText("admin")) throw new Error("Admin UI strings differ");
    console.log(`content structure checked: ${index.sources.size} sources, ${index.catalog.sections.length} sections`); return 0;
  }
  throw new Error("Invalid content command or options");
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try { process.exitCode = contentCommand(process.argv.slice(2)); } catch (error) { console.error(error instanceof Error ? error.message : "Content command failed"); process.exitCode = 1; }
}
