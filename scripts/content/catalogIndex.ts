import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

export function catalogIndexText(moduleNames: string[]) {
  const names = [...moduleNames].sort();
  return '// Generated by content:catalog-index. Do not edit imports manually.\n' +
    'import type { ContentCatalog, CoverageSection } from "../shared/content/types";\n' +
    names.map((name, index) => `import { sources as s${index} } from "./ja/guides/${name}";\nimport { records as en${index} } from "./translations/en/${name}";\nimport { records as zh${index} } from "./translations/zh-CN/${name}";\n`).join("") +
    `export const canonicalSources = [${names.map((_, index) => `...s${index}`).join(", ")}];\n` +
    `export const canonicalTranslations = { en: {${names.map((_, index) => `...en${index}`).join(", ")}}, "zh-CN": {${names.map((_, index) => `...zh${index}`).join(", ")}} };\n` +
    'export function canonicalCatalog(planned: CoverageSection[] = []): ContentCatalog {\nreturn { schemaVersion: 1, sources: canonicalSources, translations: canonicalTranslations, aliases: [], sections: [\n' +
    names.map((name, index) => `{id:${JSON.stringify(`legacy.${name}`)}, audience:"public", visibility:"active", section:{status:"registered", evidence:"legacy source migration mapping", data:s${index}.map(source=>({kind:"textRef" as const,id:source.id}))}},\n`).join("") +
    '...planned] };\n}\n';
}
export function expectedCatalogIndex() {
  const modules = readdirSync(resolve("content/ja/guides")).filter(name => name.endsWith(".ts")).map(name => name.slice(0, -3));
  for (const language of ["en", "zh-CN"]) {
    const translations = readdirSync(resolve(`content/translations/${language}`)).filter(name => name.endsWith(".ts")).map(name => name.slice(0, -3));
    if (JSON.stringify([...translations].sort()) !== JSON.stringify([...modules].sort())) throw new Error("Source/translation module mismatch");
  }
  return catalogIndexText(modules);
}
export function catalogIndexMain(args: string[]) {
  if (args.length !== 1 || !["generate", "check"].includes(args[0]!)) throw new Error("Usage: content:catalog-index generate|check");
  const expected = expectedCatalogIndex();
  const target = resolve("content/catalog.ts");
  if (args[0] === "generate") writeFileSync(target, expected);
  else if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== expected) throw new Error("Canonical index differs; run content:catalog-index generate");
  console.log(`canonical index: ${args[0]} passed`);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try { catalogIndexMain(process.argv.slice(2)); } catch (error) { console.error(error instanceof Error ? error.message : "Index failed"); process.exitCode = 1; }
}
